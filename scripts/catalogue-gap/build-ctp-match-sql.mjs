#!/usr/bin/env node
// Builds a READ-ONLY query that estimates how Collectible PinTrader (CTP)
// photos could be linked to Pin & Pop pins, to run in a project that holds
// the Pin & Pop catalogue (staging today; production after its import).
//
//   node scripts/catalogue-gap/build-ctp-match-sql.mjs <production export.csv> <out.sql>
//
// <production export.csv> is the gap report's ALL_IN_ONE download from
// production. The generated SQL embeds each active CTP pin's PinHunt ID, CTP
// id, title, series, year and edition (CTP data: licensed for any use). It is
// a working file: keep it out of git.
//
// Matching rules (nothing is linked by this query; it only proposes):
//   name    the CTP title, or its part after the last " - " ("Series - Name"),
//           equals the Pin & Pop name, or Pin & Pop "series name" equals the
//           CTP title (all compared lower-case, punctuation removed);
//   checks  year, edition type, limited-edition size and series similarity
//           decide between candidates;
//   fuzzy   CTP pins with no name match get their closest Pin & Pop names
//           (trigram similarity >= 0.6, same year) for review only.
// Output: Pin & Pop PinHunt IDs and scores only, never Pin & Pop titles.
import fs from "node:fs";
import { fileURLToPath } from "node:url";
import { sideFromFiles } from "./core.mjs";

const N = (x) => `trim(regexp_replace(replace(replace(lower(coalesce(${x}, '')), chr(8217), ''''), '&', ' and '), '[^a-z0-9]+', ' ', 'g'))`;
const q = (v) => (v === null || v === undefined || v === "" ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const num = (v) => (v === null || v === undefined || v === "" || !Number.isFinite(Number(v)) ? "null" : String(Number(v)));
const toAscii = (s) => String(s ?? "").replace(/[^\x20-\x7e]/g, (c) => `' || chr(${c.codePointAt(0)}) || '`);

export function ctpRows(production) {
  return production.pins
    .filter((p) => p.catalogue_status !== "archived")
    .map((p) => {
      const ext = String(p.external_ids ?? "");
      const m = /(?:^|;)collectible_pintrader:([^;]+)/.exec(ext);
      if (!m) return null;
      let le = null;
      try { le = JSON.parse(p.content ?? "{}").limited_edition_size ?? null; } catch { /* none */ }
      return { pinhunt_id: p.pinhunt_id, ctp_id: m[1], title: p.title, series: p.collection, year: p.release_year, edition: p.edition_type, le, has_photo: !!p.image_url };
    })
    .filter(Boolean);
}

export function buildCtpMatchSql(rows) {
  const lit = (v) => (v === null || v === undefined || v === "" ? "null" : `'${toAscii(String(v).replace(/'/g, "''"))}'`);
  const values = rows.map((r) => `  (${q(r.pinhunt_id)}, ${q(r.ctp_id)}, ${lit(r.title)}, ${lit(r.series)}, ${num(r.year)}, ${q(r.edition)}, ${num(r.le)}, ${r.has_photo})`).join(",\n");
  return `-- Collectible PinTrader photos -> Pin & Pop pins: MATCH ESTIMATE (READ-ONLY)
--
-- GENERATED by scripts/catalogue-gap/build-ctp-match-sql.mjs from the production
-- export of ${new Date().toISOString().slice(0, 10)} (${rows.length} active Collectible PinTrader pins).
-- Run in the project that holds the Pin & Pop catalogue (STAGING today).
-- It changes nothing and links nothing: it proposes, and counts how confident
-- each proposal is. Output: Pin & Pop PinHunt IDs and scores, never Pin & Pop titles.
-- Download the result as CSV and send it to Claude.

set default_transaction_read_only = on;
set pg_trgm.similarity_threshold = 0.6;

with ctp (pinhunt_id, ctp_id, title, series, yr, edition, le, has_photo) as (values
${values}
),
c as materialized (
  select ctp.*, ${N("title")} as t, ${N("series")} as s,
         ${N("case when position(' - ' in title) > 0 then regexp_replace(title, '^.* - ', '') else title end")} as nm
  from ctp
),
pp as materialized (
  select p.pinhunt_id, p.release_year as yr, p.edition_type as edition, p.limited_edition_size as le,
         ${N("p.title")} as t, ${N("p.collection")} as s, ${N("p.collection || ' ' || p.title")} as st
  from public.pins p
  where p.catalogue_source = 'pin_and_pop' and coalesce(p.catalogue_status, 'active') <> 'archived'
),
cand as (
  select c.pinhunt_id as ctp_pin, pp.pinhunt_id as pp_pin, 'name' as how,
         (c.yr is not null and pp.yr is not null and c.yr = pp.yr) as year_eq,
         (c.yr is null or pp.yr is null) as year_unknown,
         (c.edition is not null and pp.edition is not null and c.edition = pp.edition) as edition_eq,
         (c.le is not null and pp.le is not null and c.le = pp.le) as le_eq,
         (c.le is not null and pp.le is not null and c.le <> pp.le) as le_conflict,
         round(extensions.similarity(c.s, pp.s)::numeric, 2) as series_sim
  from c join (
    -- three exact joins on pre-cleaned names (an OR join can't use a hash join)
    select c1.pinhunt_id as cp, p1.pinhunt_id as pq from c c1 join pp p1 on p1.t = c1.t
    union select c2.pinhunt_id, p2.pinhunt_id from c c2 join pp p2 on p2.t = c2.nm
    union select c3.pinhunt_id, p3.pinhunt_id from c c3 join pp p3 on p3.st = c3.t
  ) m on m.cp = c.pinhunt_id
  join pp on pp.pinhunt_id = m.pq
),
ranked as (
  select cand.*,
         (case when year_eq then 4 when year_unknown then 1 else -4 end
          + case when le_eq then 3 when le_conflict then -5 else 0 end
          + case when edition_eq then 1 else 0 end
          + (series_sim * 4)) as score,
         row_number() over (partition by ctp_pin order by
           (case when year_eq then 4 when year_unknown then 1 else -4 end
            + case when le_eq then 3 when le_conflict then -5 else 0 end
            + case when edition_eq then 1 else 0 end + (series_sim * 4)) desc, pp_pin) as rk,
         count(*) over (partition by ctp_pin) as n_cand
  from cand
),
best as (
  select r1.ctp_pin, r1.pp_pin, r1.n_cand, r1.score, r1.year_eq, r1.year_unknown, r1.edition_eq, r1.le_eq, r1.le_conflict, r1.series_sim,
         r2.pp_pin as second_pin, r2.score as second_score
  from ranked r1 left join ranked r2 on r2.ctp_pin = r1.ctp_pin and r2.rk = 2
  where r1.rk = 1
),
fuzzy as (
  select c.pinhunt_id as ctp_pin, f.pp_pin, f.sim
  from c
  cross join lateral (
    select p.pinhunt_id as pp_pin, round(extensions.similarity(p.title, regexp_replace(c.title, '^.* - ', ''))::numeric, 2) as sim
    from public.pins p
    where p.catalogue_source = 'pin_and_pop'
      and p.title operator(extensions.%) regexp_replace(c.title, '^.* - ', '')
      and (c.yr is null or p.release_year is null or p.release_year = c.yr)
    order by extensions.similarity(p.title, regexp_replace(c.title, '^.* - ', '')) desc
    limit 3
  ) f
  where not exists (select 1 from best b where b.ctp_pin = c.pinhunt_id)
),
result as (
  select c.pinhunt_id as ctp_pin, c.ctp_id, c.has_photo,
         case
           when b.ctp_pin is null and not exists (select 1 from fuzzy f where f.ctp_pin = c.pinhunt_id) then 'none'
           when b.ctp_pin is null then 'fuzzy only'
           when b.le_conflict then 'conflict (edition size differs)'
           when b.year_eq and b.n_cand = 1 then 'strong (one candidate, same year)'
           when b.year_eq and b.score - coalesce(b.second_score, -99) >= 2 then 'likely (clear best of several)'
           when b.year_unknown and b.n_cand = 1 then 'possible (one candidate, year unknown)'
           when not b.year_eq and not b.year_unknown then 'weak (year differs)'
           else 'ambiguous (several close candidates)'
         end as tier,
         b.pp_pin as best_pin, b.n_cand, round(b.score::numeric, 1) as score, b.year_eq, b.edition_eq, b.le_eq, b.series_sim,
         b.second_pin, round(b.second_score::numeric, 1) as second_score,
         (select string_agg(f.pp_pin || ':' || f.sim, ';' order by f.sim desc) from fuzzy f where f.ctp_pin = c.pinhunt_id) as fuzzy_candidates
  from c left join best b on b.ctp_pin = c.pinhunt_id
)
select 'summary' as part, 0 as chunk,
       (select jsonb_object_agg(tier, n) from (select tier, count(*) n from result group by 1) s)::text as payload
union all
select 'rows', (rn - 1) / 500 + 1, json_agg(r order by rn)::text
from (select r, row_number() over (order by r.ctp_pin) rn from result r) x
group by 2
order by 1 desc, 2;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [input, out] = process.argv.slice(2);
  if (!input || !out) { console.error("Usage: build-ctp-match-sql.mjs <production export.csv> <out.sql>"); process.exit(1); }
  const production = sideFromFiles({ x: fs.readFileSync(input, "utf8") }, "production");
  const rows = ctpRows(production);
  fs.writeFileSync(out, buildCtpMatchSql(rows));
  console.log(`Wrote ${out}: ${rows.length} Collectible PinTrader pins (${rows.filter((r) => r.has_photo).length} with a photo).`);
}
