// Builds compare.html: page-template.html with core.mjs inlined, so the page
// works when opened straight from disk (browsers block module imports from
// file://). Run after changing core.mjs or the template:
//   node scripts/catalogue-gap/build-page.mjs
// compare.test.mjs fails if the committed page is out of date.
import fs from "node:fs";
import { fileURLToPath } from "node:url";

const here = (f) => fileURLToPath(new URL(f, import.meta.url));

export function buildPage() {
  const core = fs.readFileSync(here("./core.mjs"), "utf8")
    .replace(/^export /gm, "")
    .replace(/<\/script/gi, "<\\/script");
  const template = fs.readFileSync(here("./page-template.html"), "utf8");
  return template.replace("/*__CORE__*/", () => `// ── core.mjs (generated by build-page.mjs; edit core.mjs, not this) ──\n${core}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(here("./compare.html"), buildPage());
  console.log("Wrote scripts/catalogue-gap/compare.html");
}
