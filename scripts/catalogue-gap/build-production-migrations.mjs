// Builds PRODUCTION copies of the migrations that carry a staging-only guard
// (075, 076 search, 077), with the production guard from
// artifacts/api-server/scripts/PINANDPOP.md ("Production rollout", step 2) in
// its place. Everything else is byte-for-byte the original; the test checks it.
//   node scripts/catalogue-gap/build-production-migrations.mjs
import fs from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../", import.meta.url));
export const SOURCES = ["075_pinandpop_catalogue_search.sql", "076_search_catalogue_pins.sql", "077_catalogue_coverage_paged.sql"];
export const OUT_DIR = "supabase/verify/production-rollout/";

export const STAGING_GUARD = `  if not exists (select 1 from storage.buckets where id = 'pinhunt-staging-marker') then
    raise exception 'Not the staging project (no pinhunt-staging-marker bucket). Nothing was changed.';
  end if;`;

export const PRODUCTION_GUARD = `  -- PRODUCTION guard (generated copy; the original stops unless this is staging).
  if exists (select 1 from storage.buckets where id = 'pinhunt-staging-marker') then
    raise exception 'This is the staging project (it has the pinhunt-staging-marker bucket). Nothing was changed.';
  end if;
  if to_regprocedure('public.pinhunt_environment()') is null then
    raise exception 'Project marker pinhunt_environment() is missing (073_RUNBOOK.md). Nothing was changed.';
  end if;
  if (select public.pinhunt_environment()) is distinct from 'production' then
    raise exception 'This project is not production (pinhunt_environment()). Nothing was changed.';
  end if;`;

export function productionCopy(name, text) {
  const count = text.split(STAGING_GUARD).length - 1;
  if (count !== 1) throw new Error(`${name}: expected exactly one staging guard, found ${count}`);
  const header = `-- PRODUCTION COPY of supabase/migrations/${name}
-- GENERATED by scripts/catalogue-gap/build-production-migrations.mjs: identical
-- to the original except the guard, which here refuses anything but production.
-- Apply in the PRODUCTION SQL editor, in number order, after it ran on staging.

`;
  return header + text.replace(STAGING_GUARD, PRODUCTION_GUARD);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.mkdirSync(root + OUT_DIR, { recursive: true });
  for (const name of SOURCES) {
    const out = name.replace(/\.sql$/, ".PRODUCTION.sql");
    fs.writeFileSync(root + OUT_DIR + out, productionCopy(name, fs.readFileSync(root + "supabase/migrations/" + name, "utf8")));
    console.log(`Wrote ${OUT_DIR}${out}`);
  }
}
