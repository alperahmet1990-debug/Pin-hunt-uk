// Builds supabase/verify/catalogue-gap/ALL_IN_ONE.sql from queries 1-5, so a
// project needs one run and one CSV download instead of five. Run after
// changing any of the five queries:
//   node scripts/catalogue-gap/build-sql.mjs
// compare.test.mjs fails if the committed file is out of date.
import fs from "node:fs";
import { fileURLToPath } from "node:url";

const dir = fileURLToPath(new URL("../../supabase/verify/catalogue-gap/", import.meta.url));
const read = (f) => fs.readFileSync(dir + f, "utf8");
const MARK = "set default_transaction_read_only = on;";

function afterReadOnly(text) {
  const i = text.indexOf(MARK);
  if (i < 0) throw new Error("query lacks the read-only line");
  return text.slice(i + MARK.length).trim();
}
function doBlock(text) {
  const body = afterReadOnly(text);
  const end = body.indexOf("end $$;");
  if (!body.startsWith("do $$") || end < 0) throw new Error("expected a do $$ ... end $$; block");
  return body.slice(0, end + "end $$;".length);
}
function chunkQuery(text) {
  return afterReadOnly(text).replace(/;\s*$/, "").replace(/\norder by 1$/, "");
}
const indent = (s, n) => s.split("\n").map((l) => (l ? " ".repeat(n) + l : l)).join("\n");

export function buildSql() {
  return `-- Catalogue gap report: ALL FIVE QUERIES IN ONE (READ-ONLY)
--
-- GENERATED by scripts/catalogue-gap/build-sql.mjs from 1_summary.sql ...
-- 5_work.sql. Edit those, not this file.
--
-- Run once in the staging project's SQL editor and once in production's.
-- Download each result as CSV. Output columns: part, chunk, items, payload.
-- Same safety and content as the five separate queries: the session is set
-- read-only first, the only non-SELECT statements store results in temporary
-- session settings, and nothing is written to any table or file.
-- See docs/catalogue-sync/GAP-REPORT.md.

${MARK}

-- 1. Summary
${doBlock(read("1_summary.sql"))}

-- 5. Work in progress
${doBlock(read("5_work.sql"))}

-- Everything as one result: summary and work as one row each; pins, photos
-- and files in chunks of 500 records per row.
select part, chunk, items, payload
from (
  select 'summary'::text as part, 1::bigint as chunk, 1::bigint as items,
         current_setting('pinhunt.gap_summary') as payload
  union all
  select 'work', 1, 1, current_setting('pinhunt.gap_work')
  union all
  select 'pins', q.* from (
${indent(chunkQuery(read("2_pins.sql")), 4)}
  ) q
  union all
  select 'images', q.* from (
${indent(chunkQuery(read("3_images.sql")), 4)}
  ) q
  union all
  select 'files', q.* from (
${indent(chunkQuery(read("4_storage.sql")), 4)}
  ) q
) all_parts
order by case part when 'summary' then 1 when 'work' then 2 when 'pins' then 3 when 'images' then 4 else 5 end, chunk;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(dir + "ALL_IN_ONE.sql", buildSql());
  console.log("Wrote supabase/verify/catalogue-gap/ALL_IN_ONE.sql");
}
